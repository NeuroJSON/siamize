"""Regenerate src/dkatlas_weights.inc from brainchop's DKatlas model.bin.

usage: python tools/dkatlas/gen_weights.py model.bin > src/dkatlas_weights.inc

model.bin: https://github.com/neuroneural/brainchop-models/raw/main/meshnet/
model24chan104cls_synth/model.bin (raw little-endian float32, the TF.js
manifest's order; MIT, see src/dkatlas_LICENSE.txt). The floats are written
as their exact bit patterns.
"""
import hashlib
import sys

import numpy as np

raw = open(sys.argv[1], "rb").read()
w = np.frombuffer(raw, dtype="<u4")
print("// generated by tools/dkatlas/gen_weights.py -- do not edit")
print(
    "// brainchop DKatlas (model24chan104cls_synth) model.bin, %d floats, sha256 %s"
    % (w.size, hashlib.sha256(raw).hexdigest())
)
for i in range(0, w.size, 8):
    print(" ".join("0x%08x," % v for v in w[i : i + 8]))
